"""Render a Report as terminal text, GitHub-ready Markdown, standalone HTML, or JSON."""
from __future__ import annotations

import copy
import hashlib
import html
import json
import re
from dataclasses import asdict

from .analyze import Report


def _usd(x) -> str:
    return "n/a" if x is None else f"${x:,.2f}"


def _tok(n: int) -> str:
    for unit, div in (("B", 1e9), ("M", 1e6), ("k", 1e3)):
        if n >= div:
            return f"{n / div:.1f}{unit}"
    return str(n)


def redact(r: Report, keep_projects: bool = False) -> Report:
    """Strip anything private before sharing: paths, session ids, optionally project names."""
    r = copy.deepcopy(r)
    alias = {}

    def a(name):
        if keep_projects:
            return name
        if name not in alias:
            alias[name] = f"project-{hashlib.sha1(name.encode()).hexdigest()[:5]}"
        return alias[name]

    names = {p["project"] for p in r.projects}
    for p in r.projects:
        p["project"] = a(p["project"])
    for s in r.sessions_top:
        s["project"] = a(s["project"]); s["session"] = "…"
    for f in r.findings:
        if f["scope"] in names:
            f["scope"] = a(f["scope"])
        for k in sorted(names, key=len, reverse=True):
            pat = re.compile(rf"(?<![\w-]){re.escape(k)}(?![\w-])")
            f["title"] = pat.sub(a(k), f["title"])
            f["evidence"] = pat.sub(a(k), f["evidence"])
    return r


def terminal(r: Report) -> str:
    L = [f"Token audit  {r.period_start} → {r.period_end}",
         f"Spend {_usd(r.total_cost)}   Tokens {_tok(r.total_tokens)}",
         ""]
    save = sum(f["savings_usd"] for f in r.findings)
    if r.total_cost:
        L.append(f"Possible savings: up to {_usd(min(save, r.total_cost))} ({min(save, r.total_cost) / r.total_cost:.0%} of spend; findings overlap)\n")
    L.append("PROJECTS")
    for p in r.projects[:12]:
        c = "–" if p["commits"] is None else str(p["commits"])
        L.append(f"  {p['project'][:28]:<28} {_usd(p['cost']):>11}  commits {c:>4}  "
                 f"cache {p['cache_hit']:.0%}  {p['verdict']}")
    L.append("\nTOP FINDINGS")
    for i, f in enumerate(r.findings[:8], 1):
        L.append(f"  {i}. [{f['severity']}] {f['title']}  (save ~{_usd(f['savings_usd'])})")
        L.append(f"     fix: {f['fix']}")
    if r.tools:
        L.append("\nTOOLS BY CONTEXT COST")
        for t in r.tools[:6]:
            L.append(f"  {t['tool'][:30]:<30} {t['calls']:>6} calls  {_tok(t['tokens_added']):>7} added  "
                     f"{_usd(t['carry_cost']):>10} carried")
    for n in r.notes:
        L.append(f"\nnote: {n}")
    return "\n".join(L)


def markdown(r: Report, title: str = "Token Audit") -> str:
    save = sum(f["savings_usd"] for f in r.findings)
    L = [f"# {title}", "",
         f"Period **{r.period_start} to {r.period_end}**. Generated by "
         f"[tokenaudit](https://github.com/sattaru/tokenaudit) on {r.generated[:10]}.", "",
         "| Spend (list price) | Tokens | Possible savings (upper bound) | Projects |",
         "|---:|---:|---:|---:|",
         f"| {_usd(r.total_cost)} | {_tok(r.total_tokens)} | {_usd(save)} | {len(r.projects)} |", "",
         "## Was it worth it?", "",
         "| Project | Spend | Commits | $/commit | Cache hit | Score | Verdict |",
         "|---|---:|---:|---:|---:|---:|---|"]
    for p in r.projects[:20]:
        L.append(f"| {p['project']} | {_usd(p['cost'])} | {'–' if p['commits'] is None else p['commits']} | "
                 f"{_usd(p['cost_per_commit']) if p['cost_per_commit'] else '–'} | {p['cache_hit']:.0%} | "
                 f"{'–' if p['score'] is None else p['score']} | {p['verdict']} |")
    L += ["", "## What to change", ""]
    for i, f in enumerate(r.findings[:10], 1):
        L += [f"**{i}. {f['title']}** · {f['severity']} · save ~{_usd(f['savings_usd'])}", "",
              f"- Evidence: {f['evidence']}", f"- Fix: {f['fix']}", ""]
    if r.tools:
        L += ["## Where context goes (tool output)", "",
              "| Tool | Calls | Tokens added | Carry cost |", "|---|---:|---:|---:|"]
        for t in r.tools[:10]:
            L.append(f"| `{t['tool']}` | {t['calls']:,} | {_tok(t['tokens_added'])} | {_usd(t['carry_cost'])} |")
        L.append("")
    L += ["## By model", "", "| Model | Spend | Tokens |", "|---|---:|---:|"]
    for m, v in list(r.by_model.items())[:10]:
        L.append(f"| {m} | {_usd(v['cost'])} | {_tok(v['tokens'])} |")
    L += ["", "## By tool / app", "", "| Client | Spend | Tokens |", "|---|---:|---:|"]
    for m, v in r.by_client.items():
        L.append(f"| {m} | {_usd(v['cost'])} | {_tok(v['tokens'])} |")
    mix = r.token_mix; tot = sum(v for k, v in mix.items() if k != "reasoning") or 1
    L += ["", "## Token mix", "",
          " · ".join(f"{k.replace('_', ' ')} {v / tot:.0%}" for k, v in mix.items() if k != "reasoning"), ""]
    L += ["## Notes", ""] + [f"- {n}" for n in r.notes]
    return "\n".join(L) + "\n"


def html_page(r: Report, title: str = "Token Audit") -> str:
    e = html.escape
    save = sum(f["savings_usd"] for f in r.findings)
    days = list(r.by_day.items())[-60:]
    mx = max((v for _, v in days), default=1) or 1
    bw = 640 / max(len(days), 1)
    bars = "".join(f'<rect x="{i * bw:.1f}" y="{120 - v / mx * 110:.1f}" width="{max(bw - 2, 1):.1f}" '
                   f'height="{v / mx * 110:.1f}" rx="2"><title>{d}: ${v:.2f}</title></rect>'
                   for i, (d, v) in enumerate(days))
    pm = max((p["cost"] for p in r.projects), default=1) or 1
    prow = "".join(
        f"<tr><td>{e(p['project'])}</td><td class=n>{_usd(p['cost'])}</td>"
        f"<td><div class=bar style='width:{p['cost'] / pm * 100:.0f}%'></div></td>"
        f"<td class=n>{'–' if p['commits'] is None else p['commits']}</td>"
        f"<td class=n>{_usd(p['cost_per_commit']) if p['cost_per_commit'] else '–'}</td>"
        f"<td class=n>{p['cache_hit']:.0%}</td>"
        f"<td><span class='v v{(p['verdict'] or 'x')[0]}'>{e(p['verdict'])}</span></td></tr>"
        for p in r.projects[:25])
    frow = "".join(
        f"<div class='f {f['severity']}'><div class=ft><b>{e(f['title'])}</b>"
        f"<span>save ~{_usd(f['savings_usd'])}</span></div>"
        f"<p>{e(f['evidence'])}</p><p class=fix>{e(f['fix'])}</p></div>" for f in r.findings[:12])
